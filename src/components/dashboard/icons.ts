export function getOrgTypeLabel(type: string): string {
  switch (type) {
    case 'elementary_school':
      return 'دبستان';
    case 'secondary_school':
      return 'دبیرستان';
    case 'general_school':
      return 'مجتمع آموزشی';
    case 'independent_institute':
      return 'آموزشگاه آزاد';
    default:
      return 'مرکز آموزشی';
  }
}

